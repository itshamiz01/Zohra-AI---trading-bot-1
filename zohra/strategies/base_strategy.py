import time
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Dict, Any, Optional, List, Tuple
import pandas as pd

from zohra.core.market_regime import MarketRegime, RegimeReport
from zohra.core.enums import StrategyGroup, StrategyName, Direction


@dataclass
class CandidateSignal:
    """Standardized normalized signal generated by any of the 15 strategies."""
    strategy_name: str
    symbol: str
    direction: str                      # "BUY" or "SELL"
    entry_price: float
    stop_loss: float
    take_profit: float
    risk_reward: float
    stop_distance_pips: float
    setup_quality: int                  # 0 to 100
    confidence: int                     # 0 to 100
    regime_match_score: int             # 0 to 100
    volatility_score: int               # 0 to 100
    spread_score: int                   # 0 to 100
    reasons: List[str] = field(default_factory=list)
    strategy_group: str = StrategyGroup.TREND.value
    timestamp: float = field(default_factory=time.time)
    is_valid: bool = True
    invalidation_level: float = 0.0
    stop_reference: str = ""
    target_reference: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)


# Backward-compatible alias
StrategySignal = CandidateSignal


class BaseStrategy(ABC):
    """
    Abstract Base Class for all 15 ZOHRA Scalping Strategies.
    Enforces regime eligibility checks, strict data validation, and normalized candidate signals.
    """

    def __init__(self, name: str, strategy_group: StrategyGroup, allowed_regimes: List[MarketRegime]):
        self.name = name
        self.strategy_group = strategy_group
        self.allowed_regimes = allowed_regimes

    def is_eligible(self, regime_report: RegimeReport) -> Tuple[bool, str]:
        """
        Determines whether this strategy is permitted to run under the current market regime.
        """
        if regime_report.regime in self.allowed_regimes:
            return True, f"Regime {regime_report.regime.value} matches allowed regimes."
        return False, f"Regime {regime_report.regime.value} not allowed for {self.name}."

    def check_eligibility(self, regime_info: Any) -> Tuple[bool, str]:
        """Adapter for backward compatibility with dictionary or RegimeReport inputs."""
        if isinstance(regime_info, RegimeReport):
            return self.is_eligible(regime_info)
        elif isinstance(regime_info, dict):
            regime = regime_info.get("regime")
            if isinstance(regime, str):
                for m in MarketRegime:
                    if m.value == regime:
                        regime = m
                        break
            if regime in self.allowed_regimes:
                return True, f"Regime {getattr(regime, 'value', regime)} is eligible."
            return False, f"Regime {getattr(regime, 'value', regime)} not eligible for {self.name}."
        return False, "Unknown regime format."

    def generate_signal(self, df_entry: pd.DataFrame, symbol: str,
                        df_htf: Optional[pd.DataFrame] = None,
                        current_spread_pips: float = 2.0) -> Optional[CandidateSignal]:
        """Compatibility entry point for callers predating ``evaluate``.

        Strategy implementations now receive a structured regime report.  The
        public adapter preserves the old two-argument call while keeping the
        hard symbol guard and the same eligibility filter used by the suite.
        """
        from zohra.core.market_regime import market_regime_engine
        from zohra.core.symbol_resolver import CANONICAL_GOLD, symbol_resolver

        clean_symbol = str(symbol or "").strip().upper()
        is_gold_variant = clean_symbol.startswith(CANONICAL_GOLD) or clean_symbol.startswith("GOLD")
        if (
            not symbol_resolver.is_symbol_allowed(symbol)
            or not is_gold_variant
            or df_entry is None
            or df_entry.empty
        ):
            return None
        regime_report = market_regime_engine.classify_regime(
            df_entry, df_htf, current_spread_pips=current_spread_pips
        )
        eligible, _ = self.is_eligible(regime_report)
        if not eligible:
            return None
        return self.evaluate(df_entry, df_htf, regime_report, current_spread_pips=current_spread_pips)

    @abstractmethod
    def evaluate(self, df_entry: pd.DataFrame, df_htf: Optional[pd.DataFrame],
                 regime_report: RegimeReport, current_spread_pips: float = 2.0) -> Optional[CandidateSignal]:
        """
        Evaluates current completed candle data for trade setup triggers.
        Returns a CandidateSignal if a valid, confirmed setup occurs, otherwise None.
        """
        pass
